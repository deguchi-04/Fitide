import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = ts.transpileModule(readFileSync(new URL('../lib/personal-tracking.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { ingredientKey, shoppingList, frequentIngredients, exerciseKey, latestExerciseSets, adaptExercise } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const ingredient = (name, grams) => ({ name, grams });
const meals = [{ createdAt: '2026-09-01', ingredients: [ingredient('Maçã',100), ingredient('Arroz cozido',150)] }, { createdAt:'2026-09-02', ingredients:[ingredient('maça',80),ingredient('Arroz cru',50)] }];
assert.equal(ingredientKey(' Maçã '), 'maca');
assert.equal(shoppingList(meals).find(i => i.key === 'maca').grams,180);
assert.equal(shoppingList(meals).length,3);
assert.equal(frequentIngredients(meals)[0].count,2);
assert.equal(frequentIngredients(meals)[0].ingredient.grams,80);
const exercise = { name: 'Supino', equipment: 'Barra', weightKg:20, reps:'12' };
const key=exerciseKey(exercise);
const sessions=[{ date:'2026-09-01',exercises:[{ key, sets:[{load:50,reps:8}] }] }, { date:'2026-09-03',exercises:[{key,sets:[{load:45,reps:10},{load:40,reps:12}]}] }, {date:'2026-09-04'}];
assert.deepEqual(latestExerciseSets(exercise,sessions),[{load:45,reps:10},{load:40,reps:12}]);
assert.deepEqual(latestExerciseSets({...exercise,equipment:'Halteres'},sessions),[]);
assert.equal(adaptExercise(exercise,sessions).weightKg,45);
assert.equal(adaptExercise(exercise,sessions).reps,'10');
assert.equal(latestExerciseSets(exercise,sessions,'2026-09-02')[0].load,50);
console.log('Personal tracking: 10 checks passed');
